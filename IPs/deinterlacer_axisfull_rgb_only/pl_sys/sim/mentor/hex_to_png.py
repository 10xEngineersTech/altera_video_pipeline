import numpy as np
from PIL import Image

# --- Configuration ---
HEX_FILE = 'video_dump.hex'  # Path to the file generated by Questa
OUTPUT_PNG = 'output_frame.png'
WIDTH = 20                   # Must match your Verilog localparams
HEIGHT = 10

def convert_hex_to_png():
    # Initialize an empty list to hold our RGB pixel tuples
    pixels = []
    
    try:
        with open(HEX_FILE, 'r') as file:
            lines = file.readlines()
            
            for line in lines:
                line = line.strip()
                if not line:
                    continue
                
                # Convert the hex string to an integer
                val = int(line, 16)
                
                # --- Bit Unpacking ---
                # This assumes standard 24-bit RGB packing (R in highest byte, B in lowest)
                # If your colors look swapped (e.g., blue is red), swap the R and B shifts!
                r = (val >> 16) & 0xFF
                g = (val >> 8) & 0xFF
                b = val & 0xFF
                
                pixels.append([r, g, b])
                
    except FileNotFoundError:
        print(f"Error: Could not find {HEX_FILE}. Did the simulation finish?")
        return

    # Check if we have the correct number of pixels
    expected_pixels = WIDTH * HEIGHT
    if len(pixels) < expected_pixels:
        print(f"Warning: Expected {expected_pixels} pixels, but only found {len(pixels)}.")
    
    # Truncate to the exact frame size just in case we captured too much data
    pixels = pixels[:expected_pixels]

    # Convert the 1D list of pixels into a 3D numpy array (Height x Width x 3 color channels)
    # dtype=np.uint8 ensures the values are treated as standard 8-bit color values
    image_array = np.array(pixels, dtype=np.uint8).reshape((HEIGHT, WIDTH, 3))

    # Create the image using Pillow and save it
    img = Image.fromarray(image_array, 'RGB')
    
    # Optional: Because a 20x10 image is incredibly tiny, we can scale it up 
    # using nearest-neighbor interpolation so it's easier to view on your monitor.
    img_scaled = img.resize((WIDTH * 20, HEIGHT * 20), Image.NEAREST)
    
    img_scaled.save(OUTPUT_PNG)
    print(f"Success! Image saved as {OUTPUT_PNG}")

if __name__ == '__main__':
    convert_hex_to_png()
