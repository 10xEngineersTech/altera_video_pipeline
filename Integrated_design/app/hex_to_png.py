#!/usr/bin/python3
import cv2
import numpy as np
import os

def load_config(config_file):
    """
    Parses the pipeline_config.txt generated by the GUI to get
    the dynamic hardware parameters.
    """
    cfg = {}
    if not os.path.exists(config_file):
        print(f"Warning: Configuration file {config_file} not found. Using defaults.")
        return {"scale_w": 64, "scale_h": 64} # Fallback defaults

    with open(config_file, 'r') as f:
        for line in f:
            if '=' in line:
                name, value = line.split('=')
                val_str = value.strip()
                if val_str.lower() == 'true':
                    cfg[name.strip()] = True
                elif val_str.lower() == 'false':
                    cfg[name.strip()] = False
                else:
                    try:
                        cfg[name.strip()] = int(val_str)
                    except ValueError:
                        cfg[name.strip()] = val_str
    return cfg

def convert_hex_rgb_to_png(input_file, output_file, width, height):
    # 1. Load the hex strings from the file
    if not os.path.exists(input_file):
        print(f"Error: Input file {input_file} not found.")
        return

    with open(input_file, 'r') as f:
        hex_data = f.read().split()

    if len(hex_data) < width * height:
        print(f"Error: Not enough data. Expected {width*height} pixels, found {len(hex_data)}")
        pixels_to_process = len(hex_data)
    else:
        pixels_to_process = width * height

    # 2. Parse hex pixels: tdata[23:0] = {R[7:0], G[7:0], B[7:0]}
    #    $fwrite "%h" prints MSB first, so hex_val[0:2]=R, [2:4]=G, [4:6]=B
    raw_list = []
    for i in range(pixels_to_process):
        hex_val = hex_data[i].zfill(6)
        r = int(hex_val[0:2], 16)
        g = int(hex_val[2:4], 16)
        b = int(hex_val[4:6], 16)
        raw_list.append([b, g, r])  # OpenCV BGR order

    while len(raw_list) < width * height:
        raw_list.append([0, 0, 0])  # black pixel

    # 3. Create BGR NumPy array and save directly — no color conversion needed
    bgr_np = np.array(raw_list, dtype=np.uint8).reshape((height, width, 3))
    cv2.imwrite(output_file, bgr_np)
    print(f"Success! RGB image saved as {output_file}")
    print(f"Dimensions used: {width}x{height}")

# --- Dynamic Path Configuration ---
if __name__ == "__main__":
    base_dir = os.path.dirname(os.path.abspath(__file__))
    CONFIG_FILE = os.path.join(base_dir, "pipeline_config.txt")
    params = load_config(CONFIG_FILE)

    WIDTH  = params.get('scale_w', 64)
    HEIGHT = params.get('scale_h', 64)

    INPUT_TXT  = os.path.join(base_dir, "sc_data.txt")
    OUTPUT_IMG = os.path.join(base_dir, "result.png")

    convert_hex_rgb_to_png(INPUT_TXT, OUTPUT_IMG, WIDTH, HEIGHT)
