#!/usr/bin/python3
import cv2
import numpy as np
import os

def load_config(config_file):
    """
    Parses the pipeline_config.txt generated by the GUI to get 
    the dynamic hardware parameters.
    """
    cfg = {}
    if not os.path.exists(config_file):
        print(f"Warning: Configuration file {config_file} not found. Using defaults.")
        return {"scaler_width": 20, "scaler_height": 20} # Fallback defaults
        
    with open(config_file, 'r') as f:
        for line in f:
            if '=' in line:
                name, value = line.split('=')
                cfg[name.strip()] = int(value.strip())
    return cfg

def convert_hex_yuv_to_png_cv2(input_file, output_file, width, height):
    # 1. Load the hex strings from the file
    if not os.path.exists(input_file):
        print(f"Error: Input file {input_file} not found.")
        return

    with open(input_file, 'r') as f:
        hex_data = f.read().split()
    
    # Check if we have enough data for the requested dimensions
    if len(hex_data) < width * height:
        print(f"Error: Not enough data. Expected {width*height} pixels, found {len(hex_data)}")
        # We continue anyway with what we have to avoid crashing
        pixels_to_process = len(hex_data)
    else:
        pixels_to_process = width * height

    # 2. Convert hex strings to a flat list of integers (8-bit Y, U, V)
    raw_list = []
    for i in range(pixels_to_process):
        # zfill(6) ensures we handle 0x123 as 000123
        hex_val = hex_data[i].zfill(6) 
        
        # Mapping based on your hardware output format (U-Y-V)
        u = int(hex_val[0:2], 16)
        y = int(hex_val[2:4], 16)
        v = int(hex_val[4:6], 16)
        raw_list.append([y, u, v])
    
    # If the file was short, pad the rest with black pixels
    while len(raw_list) < width * height:
        raw_list.append([0, 128, 128]) # Y=0, U/V=128 is black in YUV

    # 3. Create a NumPy array and reshape to image dimensions
    yuv_np = np.array(raw_list, dtype=np.uint8).reshape((height, width, 3))

    # 4. Use OpenCV to convert YUV to BGR
    # We use YUV2BGR directly. 
    # Note: If colors look "wrong" (pink/green), try COLOR_YCrCb2BGR
    rgb = cv2.cvtColor(yuv_np, cv2.COLOR_YUV2RGB)

    # 5. Save the final image
    cv2.imwrite(output_file, rgb)
    print(f"Success! OpenCV converted image saved as {output_file}")
    print(f"Dimensions used: {width}x{height}")

# --- Dynamic Path Configuration ---
if __name__ == "__main__":
    # Get the directory where this script is located
    base_dir = os.path.dirname(os.path.abspath(__file__))
    
    # Path to the config file generated by your GUI
    CONFIG_FILE = os.path.join(base_dir, "pipeline_config.txt")
    
    # Load parameters from the config file
    params = load_config(CONFIG_FILE)
    
    # IMPORTANT: We use the SCALER dimensions because that is the 
    # output of your hardware pipeline (sc_data.txt)
    WIDTH  = params.get('scaler_width', 20)
    HEIGHT = params.get('scaler_height', 20)
    
    INPUT_TXT  = os.path.join(base_dir, "sc_data.txt")
    OUTPUT_IMG = os.path.join(base_dir, "result.png")

    convert_hex_yuv_to_png_cv2(INPUT_TXT, OUTPUT_IMG, WIDTH, HEIGHT)
