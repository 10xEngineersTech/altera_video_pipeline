`timescale 1 ns / 1 ps

module tb();

    localparam IMG_WIDTH    = 640;
    localparam IMG_HEIGHT   = 480;
    localparam SCALER_OUT_W = 64;
    localparam SCALER_OUT_H = 48;
    localparam CLK_PERIOD   = 10;
    localparam END_TIME     = IMG_WIDTH * IMG_HEIGHT * 500;

    // ?? Clock and Reset ???????????????????????????????????????????????????????
    reg clk   = 0;
    reg reset = 1;
    always #(CLK_PERIOD/2) clk = ~clk;

    // ?? Output signals ????????????????????????????????????????????????????????
    wire [23:0] out_tdata;
    wire        out_tvalid;
    reg         out_tready = 0;
    wire        out_tlast;
    wire [2:0]  out_tuser;
    wire        frame_done;

    // ?? AXI4-S Lite image input ???????????????????????????????????????????????
    reg  [23:0] img_tdata  = 24'h0;
    reg         img_tvalid = 1'b0;
    wire        img_tready;
    reg         img_tlast  = 1'b0;
    reg  [2:0]  img_tuser  = 3'b0;

    // ?? Capture output ????????????????????????????????????????????????????????
    make_file #(
        .IMG_H    (SCALER_OUT_H),
        .IMG_W    (SCALER_OUT_W),
        .IS_FULL  (0),
        .FILE_NAME("/mnt/ssd2/Izaan/altera_video_pipeline/Integrated_design/app/sc_data.txt")
    ) scaler_out (
        .clk        (clk),
        .reset      (reset),
        .tdata      (out_tdata),
        .tvalid     (out_tvalid),
        .tready     (out_tready & (dut.current_state == dut.ST_WORKING)),
        .tlast      (out_tlast),
        .tuser      (out_tuser),
        .frame_done (frame_done)
    );

    // ?? DUT ???????????????????????????????????????????????????????????????????
    top #(
        .IMG_WIDTH   (IMG_WIDTH),
        .IMG_HEIGHT  (IMG_HEIGHT),
        .SCALER_OUT_W(SCALER_OUT_W),
        .SCALER_OUT_H(SCALER_OUT_H)
    ) dut (
        .clk        (clk),
        .reset      (reset),
        .out_tdata  (out_tdata),
        .out_tvalid (out_tvalid),
        .out_tready (out_tready),
        .out_tlast  (out_tlast),
        .out_tuser  (out_tuser),
        .img_tdata  (img_tdata),
        .img_tvalid (img_tvalid),
        .img_tready (img_tready),
        .img_tlast  (img_tlast),
        .img_tuser  (img_tuser)
    );

    // ?? Stimulus ??????????????????????????????????????????????????????????????
    initial begin
        reset = 1;
        repeat(10) @(posedge clk);
        reset = 0;
        $display("[%0t] Reset released.", $time);

        wait(dut.current_state == dut.ST_WORKING);
        $display("[%0t] ST_WORKING ? pipeline configured.", $time);

        @(posedge clk);
        out_tready = 1;
    end

    // ?? Image hex player ??????????????????????????????????????????????????????
    reg [23:0] img_mem [0 : IMG_WIDTH * IMG_HEIGHT - 1];
    integer px, py;

    initial begin
        $readmemh("/mnt/ssd2/Izaan/altera_video_pipeline/Integrated_design/app/image_data.txt",
                  img_mem);
        $display("[IMG] Image loaded (%0dx%0d).", IMG_WIDTH, IMG_HEIGHT);

        wait(dut.current_state == dut.ST_WORKING);
        repeat(5) @(posedge clk);

        $display("[IMG] Sending image...");
        @(posedge clk); #1;

        for (py = 0; py < IMG_HEIGHT; py = py + 1) begin
            for (px = 0; px < IMG_WIDTH; px = px + 1) begin
                img_tdata  = img_mem[py * IMG_WIDTH + px];
                img_tvalid = 1'b1;
                // SOF on first pixel of first line
                img_tuser  = (px == 0 && py == 0) ? 3'b001 : 3'b000;
                // EOL on last pixel of each line
                img_tlast  = (px == IMG_WIDTH - 1) ? 1'b1 : 1'b0;

                @(posedge clk);
                while (!img_tready) @(posedge clk);
                #1;
            end
        end

        img_tvalid = 1'b0;
        img_tlast  = 1'b0;
        img_tuser  = 3'b0;
        $display("[IMG] Image sent.");

        wait(frame_done);
        $display("[%0t] Frame written to sc_data.txt.", $time);
        $finish;
    end

    // ?? State trace ???????????????????????????????????????????????????????????
    reg [3:0] last_state = 4'hF;
    always @(posedge clk) begin
        if (!reset && dut.current_state !== last_state) begin
            $display("[%0t] STATE %0d->%0d cfg_step=%0d",
                     $time, last_state, dut.current_state, dut.cfg_step);
            last_state <= dut.current_state;
        end
    end

    // ?? Timeout watchdog ??????????????????????????????????????????????????????
    initial begin
        #(END_TIME);
        $display("ERROR: Timeout! state=%0d cfg_step=%0d bridge_wait=%b pc1_wait=%b",
                 dut.current_state, dut.cfg_step,
                 dut.bridge_wait, dut.pc1_wait);
        $finish;
    end

endmodule
